#!/usr/bin/env python3
"""Embed exact shader source to make Theos build independent of metal CLI."""
from pathlib import Path
import hashlib
import json
base = Path(__file__).resolve().parents[1]
source = (base/'src/GFRefraction.metal').read_text(encoding='utf8')
checksum = hashlib.sha256(source.encode('utf8')).hexdigest()
lines = ['// AUTO-GENERATED by tools/embed_shader.py. DO NOT EDIT.',
         '// SHA256: '+checksum,
         'static const char *const kGFRefractionMetalSource =']
lines += ['    ' + json.dumps(line, ensure_ascii=True) for line in source.splitlines(keepends=True)]
lines += ['    ;', '']
(base/'src/GFRefractionShaderEmbedded.h').write_text('\n'.join(lines), encoding='utf8')
print(checksum)
